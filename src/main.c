static void print_help(const char *prog_name) {
    printf("Usage: %s [OPTIONS]\n\n", prog_name);
    printf("SaniGhost - High-Speed Native Multi-Pass File & DB Sanitizer\n\n");
    printf("Options:\n");
    printf("  -f, --file <path>       Target file to shred (can specify multiple)\n");
    printf("  -d, --dir <path>        Target directory to recursively shred (can specify multiple)\n");
    printf("  -b, --db <path>         Target SQLite database to sanitize and shred\n");
    printf("  -p, --passes <num>      Number of overwrite passes (default: 3, DoD standard)\n");
    printf("  -n, --dry-run           Simulate wipe without deleting data\n");
    printf("  -y, --yes               Bypass confirmation prompt\n");
    printf("  -q, --quiet             Quiet mode (suppress verbose output)\n");
    printf("  -h, --help              Display this help menu\n\n");
    printf("Example:\n");
    printf("  %s -f secret.txt -d ./evidence_folder/ -b app_cache.db -p 3 -y\n\n", prog_name);
}

static double get_time_sec(void) {
    struct timeval tv;
    gettimeofday(&tv, NULL);
    return (double)tv.tv_sec + (double)tv.tv_usec / 1000000.0;
}

int main(int argc, char *argv[]) {
    char *files[256];
    char *dirs[256];
    char *dbs[256];
    int file_count = 0, dir_count = 0, db_count = 0;

    ShredderConfig config = {
        .passes = 3,
        .dry_run = false,
        .verbose = true
    };
    bool bypass_confirm = false;

    static struct option long_options[] = {
        {"file",    required_argument, 0, 'f'},
        {"dir",     required_argument, 0, 'd'},
        {"db",      required_argument, 0, 'b'},
        {"passes",  required_argument, 0, 'p'},
        {"dry-run", no_argument,       0, 'n'},
        {"yes",     no_argument,       0, 'y'},
        {"quiet",   no_argument,       0, 'q'},
        {"help",    no_argument,       0, 'h'},
        {0, 0, 0, 0}
    };

    int opt;
    while ((opt = getopt_long(argc, argv, "f:d:b:p:nyqh", long_options, NULL)) != -1) {
        switch (opt) {
            case 'f':
                if (file_count < 256) files[file_count++] = optarg;
                break;
            case 'd':
                if (dir_count < 256) dirs[dir_count++] = optarg;
                break;
            case 'b':
                if (db_count < 256) dbs[db_count++] = optarg;
                break;
            case 'p':
                config.passes = atoi(optarg);
                if (config.passes < 1) config.passes = 1;
                break;
            case 'n':
                config.dry_run = true;
                break;
            case 'y':
                bypass_confirm = true;
                break;
            case 'q':
                config.verbose = false;
                break;
            case 'h':
            default:
                puts(BANNER);
                print_help(argv[0]);
                return 0;
        }
    }

    if (file_count == 0 && dir_count == 0 && db_count == 0) {
        puts(BANNER);
        print_help(argv[0]);
        return 0;
    }

    if (config.verbose) {
        puts(BANNER);
    }

    if (!bypass_confirm && !config.dry_run) {
        printf("\033[1;31m[!] WARNING: Confirm permanent unrecoverable data destruction? (y/N): \033[0m");
        fflush(stdout);
        char answer[16];
        if (!fgets(answer, sizeof(answer), stdin) || (answer[0] != 'y' && answer[0] != 'Y')) {
            printf("\033[1;33m[*] Operation cancelled by user.\033[0m\n");
            return 0;
        }
    }

    SanitizeStats stats = {0};
    stats.start_time = get_time_sec();

    if (config.verbose) {
        printf("\033[1;36m[*] Initiating native POSIX forensic data sanitization...\033[0m\n");
    }

    /* 1. Target files */
    for (int i = 0; i < file_count; i++) {
        shred_file(files[i], &config, &stats);
    }

    /* 2. Target SQLite databases */
    for (int i = 0; i < db_count; i++) {
        sanitize_sqlite_db(dbs[i], &config, &stats);
    }

    /* 3. Target directories */
    for (int i = 0; i < dir_count; i++) {
        shred_directory(dirs[i], &config, &stats);
    }

    stats.end_time = get_time_sec();
    double elapsed = stats.end_time - stats.start_time;

    printf("\033[1;32m[+] Sanitization complete in %.3fs. Shredded %lu files (%lu bytes overwritten, %lu DBs). Errors: %lu\033[0m\n",
           elapsed, (unsigned long)stats.files_shredded, (unsigned long)stats.bytes_overwritten, 
           (unsigned long)stats.dbs_sanitized, (unsigned long)stats.errors);

    return (stats.errors > 0) ? 1 : 0;
}
